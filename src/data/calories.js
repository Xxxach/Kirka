export const norm = (value) => value.toLowerCase().replace(/ё/g, 'е').trim();

export const portionNutrition = (item, grams, count = 1) => {
  const k = (grams * count) / 100;
  return { kcal: item.kcal * k, p: item.p * k, f: item.f * k, c: item.c * k };
};
