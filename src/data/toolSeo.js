// «22 вида», «25 видов»: склонение слова «вид» по числу.
export const kindsText = (n) => {
  const last = n % 10;
  const word = n % 100 >= 11 && n % 100 <= 14 ? 'видов' : last === 1 ? 'вид' : last >= 2 && last <= 4 ? 'вида' : 'видов';
  return `${n} ${word}`;
};
